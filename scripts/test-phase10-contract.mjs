#!/usr/bin/env node

import { access, readFile } from "node:fs/promises";

const failures = [];
const read = (path) => readFile(path, "utf8");
const requireText = (label, source, expected) => { if (!source.includes(expected)) failures.push(`${label}: missing ${expected}`); };

const catalog = JSON.parse(await read("src/docs-registry.json"));
const publicRegistry = JSON.parse(await read("public/r/registry.json"));
const publicNames = new Set(publicRegistry.items.map((item) => item.name));
for (const item of catalog.items) if (!publicNames.has(item.name)) failures.push(`docs catalog: unknown registry item ${item.name}`);
for (const section of ["Atoms", "Molecules", "Organisms"]) if (!catalog.navigation.some((group) => group.section === section)) failures.push(`docs navigation: missing ${section}`);
if (!catalog.counts.blocks || catalog.counts.blocks !== catalog.blocks.length) failures.push("docs catalog: block count is stale");

for (const href of new Set(catalog.items.map((item) => item.href.split("#")[0]))) {
  try { await access(`${href.replace(/^\//, "app/")}/page.tsx`); } catch { failures.push(`docs route: missing ${href}`); }
}

const layout = await read("app/docs/layout.tsx");
for (const expected of ["Getting Started", "Theme", "Components", "Blocks", "Migration", "max-w-[1440px]", 'scrollMode="fade"', "docsCatalog.navigation"]) requireText("docs shell", layout, expected);
if (/componentRegistry|docsMobileNav/.test(await read("lib/navigation.ts"))) failures.push("docs navigation: manual component registry remains in lib/navigation.ts");

const sidebar = await read("components/ui/organisms/sidebar.tsx");
for (const expected of ['scrollMode?: "auto" | "hidden" | "fade"', 'data-scroll-mode={scrollMode}', 'scrollMode === "auto"', 'scrollMode === "hidden"', 'scrollMode === "fade"', "mask-image:linear-gradient"]) requireText("sidebar scroll modes", sidebar, expected);
requireText("published sidebar scroll modes", await read("registry/poyraz/ui/phase8/sidebar.tsx"), "data-scroll-mode={scrollMode}");
requireText("sidebar docs", await read("app/docs/organisms/sidebar/page.tsx"), "Content overflow");

const componentPages = (await Promise.all(["atoms", "molecules", "organisms"].map(async (group) => {
  const { readdir } = await import("node:fs/promises");
  const directories = await readdir(`app/docs/${group}`, { withFileTypes: true });
  return Promise.all(directories.filter((entry) => entry.isDirectory()).map((entry) => read(`app/docs/${group}/${entry.name}/page.tsx`)));
}))).flat();
if (componentPages.filter((source) => source.includes("<ComponentPage")).length < 40) failures.push("component pages: shared ComponentPage coverage is incomplete");

const codeBlock = await read("components/docs/code-block.tsx");
for (const expected of ["RegistryDetails", "PreviewToolbar", "previewClassName", "data-preview-background"]) requireText("component page composition", codeBlock, expected);
const details = await read("components/docs/registry-details.tsx");
for (const expected of ["shadcn@latest add @poyraz", "Runtime dependencies", "Registry dependencies", "Source", "API", "Accessibility", "navigator.clipboard"]) requireText("registry details", details, expected);
const preview = await read("components/docs/preview-context.tsx");
for (const expected of ['"solid"', '"gradient"', '"dark"', '"sharp"', '"soft"', '"round"', '"compact"', '"spacious"', '"reduced"']) requireText("preview controls", preview, expected);

requireText("button playground", await read("app/docs/atoms/button/page.tsx"), "ButtonPlayground");
for (const expected of ["variant", "size", "radius", "effect", "fillDirection"]) requireText("button playground controls", await read("components/demos/button-playground.tsx"), expected);
for (const page of ["auth", "dashboard", "hero", "pricing"]) requireText(`block preview ${page}`, await read(`app/docs/templates/${page}/page.tsx`), "BlockPreview");
for (const viewport of ["desktop", "tablet", "mobile"]) requireText("block viewport", await read("components/docs/block-preview.tsx"), viewport);

for (const route of ["blocks", "troubleshooting", "migration", "legacy/v2"]) {
  try { await access(`app/docs/${route}/page.tsx`); } catch { failures.push(`phase 10 route: missing ${route}`); }
}
for (const mode of ["light", "dark", "system"]) requireText("theme control", await read("components/theme-toggle.tsx"), `value: "${mode}"`);
requireText("README registry quick start", await read("README.md"), "V3 Registry Quick Start");
requireText("COMPONENTS generated", await read("COMPONENTS.md"), "Generated by `pnpm docs:sync`");
for (const expected of ["V3 install:", "/docs/installation", "/docs/troubleshooting"]) requireText("CLI docs links", await read("bin/cli.mjs"), expected);

const roadmap = await read("docs/v3-registry-redesign-roadmap.md");
for (let index = 1; index <= 24; index += 1) requireText("phase 10 roadmap", roadmap, `- [x] \`P10-${String(index).padStart(3, "0")}\``);

if (failures.length) {
  console.error("Phase 10 contract validation failed:\n");
  failures.forEach((failure) => console.error(`- ${failure}`));
  process.exit(1);
}
console.log(`Phase 10 contract is valid (${catalog.counts.components} components, ${catalog.counts.blocks} blocks, registry-driven docs).`);

