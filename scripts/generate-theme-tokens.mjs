import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const tokenPath = path.join(repositoryRoot, "src/theme-tokens.json");
const presetPath = path.join(repositoryRoot, "src/preset.css");
const startMarker = "/* @poyraz-tokens:start */";
const endMarker = "/* @poyraz-tokens:end */";

const source = JSON.parse(await readFile(tokenPath, "utf8"));

function toKebabCase(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Za-z])(\d+)/g, "$1-$2")
    .replace(/_/g, "-")
    .toLowerCase();
}

function variableName(parts) {
  return `--poyraz-${parts.map(toKebabCase).join("-")}`;
}

function flattenValues(value, pathParts = [], entries = []) {
  for (const [key, child] of Object.entries(value)) {
    const nextPath = [...pathParts, key];
    if (typeof child === "string") {
      entries.push([variableName(nextPath), child]);
    } else {
      flattenValues(child, nextPath, entries);
    }
  }
  return entries;
}

function cssThemeValue(value) {
  const reference = value.match(/^\{([^}]+)\}$/)?.[1];
  if (!reference) return value;

  const pathParts = reference.split(".");
  if (pathParts[0] === "primitives" || pathParts[0] === "shared") {
    return `var(${variableName(pathParts.slice(1))})`;
  }

  throw new Error(`Unsupported token reference: ${value}`);
}

function declarationBlock(selector, entries) {
  const declarations = entries
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");
  return `${selector} {\n${declarations}\n}`;
}

const primitiveEntries = flattenValues(source.primitives);
const sharedEntries = flattenValues(source.shared);
const lightEntries = Object.entries(source.themes.light).map(([key, value]) => [
  variableName([key]),
  cssThemeValue(value),
]);
const darkEntries = Object.entries(source.themes.dark).map(([key, value]) => [
  variableName([key]),
  cssThemeValue(value),
]);

const generated = [
  startMarker,
  "/* Generated by scripts/generate-theme-tokens.mjs. Do not edit this block. */",
  declarationBlock(":root", [...primitiveEntries, ...sharedEntries]),
  declarationBlock(':root,\n[data-poyraz-theme="light"]', lightEntries),
  declarationBlock('.dark,\n[data-poyraz-theme="dark"]', darkEntries),
  endMarker,
].join("\n\n");

const preset = await readFile(presetPath, "utf8");
const start = preset.indexOf(startMarker);
const end = preset.indexOf(endMarker);

if (start === -1 || end === -1 || end < start) {
  throw new Error(
    `Token markers are missing or invalid in ${path.relative(repositoryRoot, presetPath)}`,
  );
}

const currentGenerated = preset.slice(start, end + endMarker.length);
if (process.argv.includes("--check")) {
  if (currentGenerated !== generated) {
    console.error(
      "Generated theme CSS is stale. Run: node scripts/generate-theme-tokens.mjs",
    );
    process.exitCode = 1;
  } else {
    console.log("Theme CSS is synchronized with src/theme-tokens.json.");
  }
} else {
  const nextPreset = `${preset.slice(0, start)}${generated}${preset.slice(
    end + endMarker.length,
  )}`;
  await writeFile(presetPath, nextPreset);
  console.log("Generated theme CSS in src/preset.css.");
}

